#!/bin/sh
set -eu
# Atomically update only this service's chains; preserve every other rule.
iptables-restore --noflush <<'RULES'
*filter
:AFEIII-WEBCHECK - [0:0]
:AFEIII-WEBCHECK-HOST - [0:0]
-F AFEIII-WEBCHECK
-F AFEIII-WEBCHECK-HOST
-A AFEIII-WEBCHECK -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
-A AFEIII-WEBCHECK -d 0.0.0.0/8 -j REJECT
-A AFEIII-WEBCHECK -d 10.0.0.0/8 -j REJECT
-A AFEIII-WEBCHECK -d 100.64.0.0/10 -j REJECT
-A AFEIII-WEBCHECK -d 127.0.0.0/8 -j REJECT
-A AFEIII-WEBCHECK -d 169.254.0.0/16 -j REJECT
-A AFEIII-WEBCHECK -d 172.16.0.0/12 -j REJECT
-A AFEIII-WEBCHECK -d 192.0.0.0/24 -j REJECT
-A AFEIII-WEBCHECK -d 192.168.0.0/16 -j REJECT
-A AFEIII-WEBCHECK -d 198.18.0.0/15 -j REJECT
-A AFEIII-WEBCHECK -d 224.0.0.0/4 -j REJECT
-A AFEIII-WEBCHECK -d 240.0.0.0/4 -j REJECT
-A AFEIII-WEBCHECK -p tcp -m multiport --dports 53,80,443 -j ACCEPT
-A AFEIII-WEBCHECK -p udp --dport 53 -j ACCEPT
-A AFEIII-WEBCHECK -j REJECT
-A AFEIII-WEBCHECK-HOST -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT
-A AFEIII-WEBCHECK-HOST -j REJECT
COMMIT
RULES
iptables -C DOCKER-USER -i br-webcheck -j AFEIII-WEBCHECK 2>/dev/null || iptables -I DOCKER-USER 1 -i br-webcheck -j AFEIII-WEBCHECK
iptables -C INPUT -i br-webcheck -j AFEIII-WEBCHECK-HOST 2>/dev/null || iptables -I INPUT 1 -i br-webcheck -j AFEIII-WEBCHECK-HOST
